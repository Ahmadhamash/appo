export function phaseEightSafeErrorLabel(locale: SupportedLocale, code: string): string {
  const refusal = predictiveRefusalReasons.find((reason) => reason === code);
  if (refusal) return phaseEightRefusalLabel(locale, refusal);
  if (code === "PARTIAL_EVIDENCE_ON_RETRY") {
    return locale === "ar"
      ? "أُغلقت الأدلة الجزئية بأمان؛ أنشئ مهمة جديدة بدلاً من خلط نتائج من إعدادات مختلفة."
      : "Partial evidence was sealed safely; start a new job instead of mixing configuration versions.";
  }
  if (code === "MAX_ATTEMPTS_EXCEEDED") {
    return locale === "ar"
      ? "بلغت المهمة حد إعادة المحاولة ونُقلت إلى حالة الفشل النهائي."
      : "The job reached its retry limit and moved to the dead-letter state.";
  }
  return locale === "ar"
    ? "توقفت المعالجة بأمان؛ راجع سجل التدقيق أو أعد المحاولة."
    : "Processing stopped safely; review the audit log or retry.";
}

